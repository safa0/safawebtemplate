function LogoIcon({ id }: { readonly id: string }) {
  const logo = LOGOS[id];
  if (!logo) return null;

  if (!logo.viewBox || !logo.paths) {
    return null;
  }

  return (
    <svg
      viewBox={logo.viewBox}
      fill="currentColor"
      className="h-8 w-auto sm:h-10"
      aria-label={logo.name}
      role="img"
    >
      {logo.paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}

function MarqueeRow({ logos, reverse = false }: { readonly logos: readonly string[]; readonly reverse?: boolean }) {
  const items = [...logos, ...logos];

  return (
    <div className="flex overflow-hidden [mask-image:linear-gradient(to_right,transparent,black_10%,black_90%,transparent)]">
      <div
        className={`flex shrink-0 items-center gap-12 sm:gap-16 py-4 ${
          reverse ? "animate-marquee-reverse" : "animate-marquee"
        }`}
      >
        {items.map((id, i) => (
          <div
            key={`${id}-${i}`}
            className="flex items-center gap-3 text-khaki-light/50 hover:text-khaki-light/80 transition-colors duration-300 whitespace-nowrap"
          >
            <LogoIcon id={id} />
            <span className="text-sm sm:text-base font-medium tracking-wide uppercase">
              {LOGOS[id]?.name ?? id}
            </span>
          </div>
        ))}
      </div>
      <div
        aria-hidden="true"
        className={`flex shrink-0 items-center gap-12 sm:gap-16 py-4 ${
          reverse ? "animate-marquee-reverse" : "animate-marquee"
        }`}
      >
        {items.map((id, i) => (
          <div
            key={`${id}-dup-${i}`}
            className="flex items-center gap-3 text-khaki-light/50 hover:text-khaki-light/80 transition-colors duration-300 whitespace-nowrap"
          >
            <LogoIcon id={id} />
            <span className="text-sm sm:text-base font-medium tracking-wide uppercase">
              {LOGOS[id]?.name ?? id}
            </span>
          </div>
        ))}
      </div>
    </div>
  );
}

export function LogoBanner() {
  const sectionRef = useRef<HTMLElement>(null);

  useEffect(() => {
    const ctx = gsap.context(() => {
      gsap.from(sectionRef.current, {
        opacity: 0,
        y: 20,
        duration: 0.8,
        scrollTrigger: {
          trigger: sectionRef.current,
          start: "top 90%",
          toggleActions: "play none none none",
        },
      });
    }, sectionRef);

    return () => ctx.revert();
  }, []);

  const { heading, logos } = siteConfig.partners;
  const half = Math.ceil(logos.length / 2);
  const row1 = logos.slice(0, half);
  const row2 = logos.slice(half);

  return (
    <section
      ref={sectionRef}
      className="relative py-14 sm:py-20 bg-dark/50 backdrop-blur-sm border-y border-khaki-light/10"
    >
      <p className="text-center text-xs uppercase tracking-[0.25em] text-khaki-light/50 mb-8 sm:mb-10 px-6">
        {heading}
      </p>
      <MarqueeRow logos={row1} />
      <MarqueeRow logos={row2} reverse />
    </section>
  );
}
